/**
 * 이 건물 주소를 네이버 지도에서 검색하는 링크를 만든다.
 *
 * 여기까지 두 번 막혔고, 그 기록을 남겨 둔다. 다음 사람이 같은 길을 다시 파지
 * 않도록.
 *
 * 1) 거리뷰를 바로 열려고 했다. 안 된다. 네이버 거리뷰 링크는 좌표가 아니라
 *    파노라마 ID로 자리를 나른다.
 *
 *      map.naver.com/p?c=15.00,0,0,0,adh&isMini=true&p=Z5QLR2c2qBZfA1esdiN-rg,-121,10,80,Float
 *                        ^^^^^^^ 좌표가 0,0이다     ^^^^^^^^^^^^^^^^^^^^^^ 여기가 자리다
 *
 *    그 ID는 좌표에서 계산할 수 없고 파노라마 조회 API를 불러야 나온다.
 *
 * 2) 그러면 지도만 좌표로 열자고 `?lat=..&lng=..`을 썼다. 그것도 안 된다.
 *    실측으로 확인했다. 네이버는 그 파라미터를 조용히 무시하고 사용자의
 *    마지막 위치를 띄운다. 404도 빈 화면도 아니라서 틀린 줄도 모른다.
 *    보증금을 걸고 보는 화면에서 그건 "링크가 안 됩니다"보다 훨씬 나쁘다.
 *    엉뚱한 골목을 보고 내 집이라고 믿게 된다.
 *
 * 그래서 주소 검색으로 간다. 이 방식의 값어치는 정확도가 아니라 **틀렸을 때
 * 티가 난다**는 것이다. 그러려면 검색어가 우리 화면에도 보여야 한다. 네이버
 * 화면에만 뜨면 누른 뒤에야 알기 때문이다. UnitLookup이 이 문자열을 문구 안에
 * 그대로 적는다. 그 한 줄이 이 방식의 전제다.
 *
 * 어디까지 확인했는지
 *
 *   확인함  "서울 종로구 명륜3가 1-100"(시도 붙은 꼴, 앱이 실제로 만드는 형태),
 *           "종로구 명륜3가 1-100", "평택시 팽성읍 남산리 92-10". 사람이 직접 눌러
 *           봤다(2026-08). 좌표 방식이 안 되는 것도 같은 방법으로 확인했다.
 *   못 함    산번지 143건("산87-85"처럼 붙여 쓴다. 공식 표기는 "산 87-85"),
 *           화성 신설 4구 4,871건(만세·효행·병점·동탄, 2025-07 신설이라 네이버
 *           주소 DB가 받는지 모른다).
 *
 * 둘 다 우리 지오코더(JUSO)는 같은 꼴로 찾아낸다. 산번지 93.0%(133/143),
 * 화성 4구 99.5%(4,845/4,871). 주소 문자열 자체는 성립한다는 뜻이라 그대로 낸다.
 * 못 찾더라도 화면이 검색어를 그대로 적어 두므로 사용자가 못 찾은 줄 안다.
 * 조용히 다른 건물을 보여 주는 경로가 아니다.
 *
 * SDK를 안 쓰는 이유는 그대로다.
 *   - 오프라인. 지금 리포트는 데이터가 전부 캐시라 지하철에서도 열린다.
 *   - 약관. 네이버 Maps는 응답 저장·캐싱을 막는데, 이 앱은 빌드 때 구워서 정적
 *     파일로 내보내는 것이 구조 전부다.
 *   - 약속. "계정 없음, 데이터는 기기에만"이라고 해 놓고 SDK를 심으면, 사용자가
 *     어느 집 주소를 들여다봤는지가 네이버로 간다. 전세 사기를 걱정해 검색한
 *     주소는 민감한 정보다.
 * 링크는 누를 때만 나간다. 안 누르면 아무것도 안 나간다.
 */

/** 주소 형식을 아는 곳은 여기 하나뿐이다. 네이버가 바꾸면 고칠 곳도 여기 하나다. */
const BASE = 'https://map.naver.com/p/search/'

/**
 * 시군구 이름만으로는 전국에서 안 갈린다. 중구는 서울·부산·대구·인천·대전·울산에
 * 다 있다. 앞에 시도를 붙여야 검색이 한 곳으로 떨어진다. 지금 다루는 것은 둘뿐이고,
 * 모르는 코드면 붙이지 않는다. 틀린 시도를 붙이는 것보다 안 붙이는 편이 낫다.
 */
const SIDO = { 11: '서울', 41: '경기' }

/**
 * 지번으로 성립하는 꼴. "1-100", "1", "산87-85"까지만 통과시킨다.
 *
 * 신고서의 지번 칸에 지번이 아닌 것이 들어오는 경우가 있다. 택지지구 블록번호가
 * 그렇다. 실측 전수 326,873개 중 164개가 "가-", "BL-", "BL-3-1", "지구BL" 같은
 * 값이고, 지번 칸이 아예 빈 것이 30개 더 있다. 이 검사가 194개를 막는다. 그걸 검색어로 내보내면 네이버는 "못 찾았습니다"가 아니라 그 동네 아무
 * 건물을 준다. 좌표 링크가 사용자의 현재 위치를 띄우던 것과 같은 종류의 사고이고,
 * 그 동네 남의 건물이라 더 그럴듯해서 더 나쁘다.
 *
 * 그 194건은 영통푸르지오트레센츠·고덕풍경채어바니티·판교 위너스 에비뉴 같은
 * 신축 대단지라 실제 건물명을 갖고 있다. 그래도 이름으로 대신 찾지는 않는다. 신고서 이름은
 * 표기가 제각각이라 이미 기각한 길이다. 못 찾을 바에는 버튼을 안 내민다.
 */
const JIBUN = /^산\s*\d+(-\d+)?$|^\d+(-\d+)?$/

/**
 * 검색어로 쓸 주소를 조립한다. "서울 종로구 명륜3가 1-100" 꼴이다.
 *
 * 건물명은 넣지 않는다. 신고서의 이름은 표기가 제각각이고 11.5%는 "(1-100)"처럼
 * 지번만 담고 오는데(전수 326,873개 중 37,564개), 그런 것이 검색어에 섞이면
 * 오히려 못 찾는다. 지번 주소는 그 자체로 유일하다.
 *
 * 시군구가 없으면 만들지 않는다. 법정동 이름은 시군구를 건너뛰면 안 갈린다.
 * 목동·신정동·신사동처럼 두 시군구 이상에 같은 이름이 있는 물건이 40,834건
 * (12.5%)이다. "서울 신사동 123-4"는 강남과 은평 둘 다에 있다.
 */
export function placeQuery(lawd, guName, umd, jibun) {
  // String()으로 감싸는 이유는 방어가 아니라 사고 방지다. jibun이 숫자로 오면
  // .trim()이 없어 TypeError가 나고, 그러면 링크가 아니라 리포트 카드가 통째로
  // 죽는다. 지금 전수 326,873건이 다 문자열이지만 그 대가가 너무 비싸다.
  const j = String(jibun ?? '').trim()
  const d = String(umd ?? '').trim()
  const g = String(guName ?? '').trim()
  // 동이 없으면 만들지 않는다. 시군구까지만으로 검색하면 구청이 나온다.
  // 공백만 든 값도 없는 것으로 본다. !umd는 '  '을 못 거른다.
  if (!JIBUN.test(j) || !g || !d) return ''
  return [SIDO[String(lawd).slice(0, 2)], g, d, j].filter(Boolean).join(' ')
}

/**
 * 네이버 지도 검색 URL. 검색어가 없으면 null을 준다.
 * 부르는 쪽은 null이면 버튼을 아예 안 만든다. 눌렀는데 아무 데도 안 가는 것보다
 * 없는 편이 낫다는 규칙은 앱 안 "지도로 보기"와 같다.
 *
 * encodeURIComponent를 쓰는 이유는 공백 하나 때문이다. URLSearchParams는 공백을
 * '+'로 쓰는데(form-urlencoded), 경로 조각에서는 '+'가 공백으로 안 풀려 검색어에
 * 그대로 실린다. 주소에는 반드시 공백이 들어간다.
 */
export function naverSearchUrl(query) {
  const q = (query || '').trim()
  if (!q) return null
  return BASE + encodeURIComponent(q)
}
