/**
 * 목록 행 아래 한 줄 코멘트.
 *
 * 참고 서비스의 행 문법("2019년으로 아직 새 편이고 예산에 딱 맞는 편이에요")에서
 * 형태만 가져오고 내용 규칙은 뒤집었다. 저쪽은 사람 말로 추천하고, 우리는
 * 실측으로만 말한다. 형용사 금지. 문장은 사실 + 출처다. 좋은 소식도
 * "확인된 값입니다"까지가 상한이다. "안전해요"는 우리가 할 수 있는 말이 아니다.
 *
 * 신호가 없는 행에는 코멘트를 내지 않는다. 전 행에 한 줄씩 달면 코멘트가 배경
 * 소음이 되고, "이 행엔 말이 없다"는 것 자체가 정보이기를 멈춘다.
 *
 * 임계값은 verdict.js와 같은 것만 쓴다(깡통 1.0, 판단 보류 1.5, 신축 2018,
 * 표본 3건). 여기서 다른 값을 쓰면 목록과 카드가 같은 물건에 다른 말을 한다.
 *
 * finder 열만 받는다. 상세 로드 없이 목록 렌더에서 바로 나와야 해서다.
 * 세 화면(확인·임장·동네)이 이 하나를 쓴다. 목록 문구가 화면마다 갈라지면
 * 같은 물건이 어디서 열었느냐로 다른 말을 듣는다.
 */
import { RATIO_BROKEN } from './verdict.js'

export function rowComment({ stage, ht, ns, nj, ratio, by, hike }) {
  // 전세가 없는 행은 NoJeonseSig가 이미 말한다. 여기 덧대면 두 줄이 싸운다.
  if (!nj) return null
  const villa = ht === 'R' || ht === 'O'
  // 확인된 깡통. verdict의 critical과 같은 조건이다.
  if (stage === 'A' && ns >= 3 && ratio != null && ratio >= 1.0 && ratio < RATIO_BROKEN) {
    return `매매 ${ns}건 기준, 보증금이 매매가를 넘습니다`
  }
  // 신축 무매매 전세 다수. 전세사기 물건에서 반복된 모양이고 verdict.js:89와
  // 같은 조건이다. 리뷰에서 둘이 잡혔다. R만 보던 것을 villa(오피스텔 포함)로
  // 맞췄고(어긋난 채로는 카드가 critical인 오피스텔 1,091개 행이 목록에서
  // 무신호였다), 보류 규칙보다 앞에 뒀다. 매매 0건의 ratio는 인근 추정치라
  // 1.5를 넘을 수 있는데 verdict는 그때 비율을 접고 이 판정을 먼저 낸다.
  // 순서가 뒤이면 목록만 "보류"로 내려 카드와 갈라진다(실측 61행).
  if (villa && !ns && by >= 2018 && nj >= 5) {
    return `신축인데 매매 없이 전세만 ${nj}건입니다`
  }
  if (ratio != null && ratio >= RATIO_BROKEN) {
    return '비교 기준이 깨져 판단을 보류했습니다'
  }
  // 갱신 보증금이 내렸다. 시세 하락의 직접 신호다. hike는 갱신 여러 건의
  // 중위값이라(build_units.py) 단일 계약처럼 읽히지 않게 "중위"를 밝힌다.
  if (hike != null && hike <= -0.05) {
    return `갱신 보증금이 중위 ${Math.round(-hike * 100)}% 내렸습니다`
  }
  // 아파트인데 매매가 없다. 전세 있는 아파트 열에 둘뿐인 경우다(verdict와 동일).
  // 빌라의 매매 0건은 열에 일곱이라 신호가 아니고, u-sig의 "매매 0건"이 이미 말한다.
  if (!villa && !ns) {
    return '아파트인데 최근 2년 매매가 없습니다'
  }
  // 좋은 소식도 실측 문구로만, 그리고 드물 때만. 빌라에서 이 조합(자기 매매
  // 3건 이상에 전세가율 80% 미만)은 전세 있는 빌라의 3%뿐인 신호다. 아파트는
  // stage A가 78%라 같은 조합이 기본 상태다. 기본 상태에 코멘트를 달면 확인 탭
  // 검색처럼 계약 많은 대단지가 먼저 오는 목록에서 전 행에 붙어 벽지가 된다.
  // 실측: 이 조건을 아파트에 열었더니 사당동 검색 상위 40행 전부에 코멘트가 섰다.
  if (villa && stage === 'A' && ns >= 3 && ratio != null && ratio < 0.8) {
    return `이 건물 매매 ${ns}건으로 확인된 값입니다`
  }
  return null
}
